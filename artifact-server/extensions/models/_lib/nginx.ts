/**
 * Deterministic nginx site rendering for the artifact server.
 *
 * The site serves `<root>` read-only: no autoindex, no symlink following, and
 * dotfiles and `refs/` denied (in-flight upload temp files live in the served
 * tree). TLS and basic auth are added only when the caller asked for them.
 *
 * @module
 */

import { posixQuote } from "./ssh.ts";

/** Absolute path of the generated site file. */
export const NGINX_SITE_PATH = "/etc/nginx/sites-available/artifact-server";
/** Symlink nginx loads from. */
export const NGINX_ENABLED_PATH = "/etc/nginx/sites-enabled/artifact-server";
/** Ubuntu's default site, disabled so it cannot claim the same port. */
export const NGINX_DEFAULT_SITE = "/etc/nginx/sites-enabled/default";
/** Basic-auth file; root owned, group-readable by the nginx workers. */
export const HTPASSWD_PATH = "/etc/nginx/artifact-server.htpasswd";
/** Provided TLS certificate path. */
export const TLS_CERT_PATH = "/etc/nginx/ssl/artifact-server.crt";
/** Provided TLS private key path. */
export const TLS_KEY_PATH = "/etc/nginx/ssl/artifact-server.key";

/** nginx `listen` address form: `*`, a host, or a bracketed IPv6 literal. */
export function listenAddress(address: string): string {
  if (address === "*") return "*";
  return address.includes(":") ? `[${address}]` : address;
}

/** Arguments for {@link renderSite}. */
export interface SiteArgs {
  /** Served root directory. */
  root: string;
  /** Listen address and port. */
  listen: { address: string; port: number };
  /** `server_name`. */
  serverName: string;
  /** Whether TLS is provided. */
  tlsProvided: boolean;
  /** Whether basic auth is enabled. */
  basicAuth: boolean;
  /** Basic-auth realm, used only when `basicAuth` is true. */
  basicAuthRealm: string;
}

/** Renders the nginx site configuration; byte-identical for identical inputs. */
export function renderSite(args: SiteArgs): string {
  const addr = listenAddress(args.listen.address);
  const ssl = args.tlsProvided ? " ssl" : "";
  const lines: string[] = [
    "# Generated by @randybias/artifact-server; do not edit.",
    "server {",
    `    listen ${addr}:${args.listen.port}${ssl};`,
    `    server_name ${posixQuote(args.serverName)};`,
    `    root ${posixQuote(args.root)};`,
    "    autoindex off;",
    "    disable_symlinks on;",
    "    location ~ /\\. {",
    "        deny all;",
    "    }",
    "    location ^~ /refs/ {",
    "        deny all;",
    "    }",
    "    location = /SHA256SUMS {",
    '        add_header Cache-Control "no-cache";',
    "    }",
    "    location ^~ /sha256/ {",
    '        add_header Cache-Control "public, max-age=31536000, immutable";',
    "    }",
    "    location ^~ /bundles/ {",
    '        add_header Cache-Control "public, max-age=31536000, immutable";',
    "    }",
  ];
  if (args.tlsProvided) {
    lines.push(`    ssl_certificate ${posixQuote(TLS_CERT_PATH)};`);
    lines.push(`    ssl_certificate_key ${posixQuote(TLS_KEY_PATH)};`);
  }
  if (args.basicAuth) {
    lines.push(`    auth_basic ${posixQuote(args.basicAuthRealm)};`);
    lines.push(`    auth_basic_user_file ${posixQuote(HTPASSWD_PATH)};`);
  }
  lines.push("}");
  return `${lines.join("\n")}\n`;
}
